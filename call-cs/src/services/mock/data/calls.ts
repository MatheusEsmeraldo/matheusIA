// ---------- helpers só do mock ----------
const pt = (x: number, y: number): MapPoint => ({ x, y });

function util(
  id: string,
  name: string,
  type: UtilityType,
  startPosition: string,
  targetPosition: string,
  player: PlayerCount | null,
  mapPoint: MapPoint | null,
  throwType: ThrowType = 'NORMAL',
  instructions = 'Lineup ilustrativo. Biblioteca real de lineups virá depois.',
): Utility {
  return { id, name, type, startPosition, targetPosition, throwType, instructions, videoUrl: null, player, mapPoint };
}

const role = (player: PlayerCount, position: string, responsibility: string): PlayerRole => ({
  player,
  position,
  responsibility,
});

const player = (n: PlayerCount, p: MapPoint): MapMarker => ({ id: `p${n}`, kind: 'PLAYER', label: String(n), ...p });
const target = (label: string, p: MapPoint): MapMarker => ({ id: `target-${label}`, kind: 'TARGET', label, ...p });
const path = (n: PlayerCount | null, ...points: MapPoint[]): MapPath => ({
  id: `path-${n ?? 'x'}-${points.length}-${points[0].x}`,
  player: n,
  points,
});

